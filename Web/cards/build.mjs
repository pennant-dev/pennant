// Builds the card page the apps load (Sources/PennantUI/Resources/PennantCards.html): the renderer and components
// as one script, Tailwind's CSS for them, both inline, so a card draws offline. `node build.mjs`.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../Sources/PennantUI/Resources/PennantCards.html");

const js = await build({
  entryPoints: [join(here, "src/main.tsx")],
  bundle: true,
  minify: !process.env.DEBUG,
  format: "iife",
  target: ["safari17"],
  jsx: "automatic",
  alias: { "@": join(here, "src/vendor") },
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  logOverride: { "unsupported-directive": "silent" },
  write: false,
});

const css = execFileSync(join(here, "node_modules/.bin/tailwindcss"), ["-i", join(here, "src/theme.css"), "--minify"], { cwd: here, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });

// A page that fails to start says why to the app, instead of a blank card.
const report = `window.webkit?.messageHandlers?.pennant?.postMessage({ type: "error", message: String(e) + "\\n" + String(e && e.stack) })`;
const script = `try {\n${js.outputFiles[0].text}\n} catch (e) { ${report} }`.replaceAll("</script", "<\\/script");
const html = `<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Pennant's cards: json-render (Apache-2.0) with shadcn/ui components (MIT). Built from Web/cards; don't edit. -->
<style>${css}</style></head>
<body><div id="card"></div><script>${script}</script></body></html>
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(`${out} ${(html.length / 1024).toFixed(0)} KB`);

// The catalog for the host: the components the model may use and their props' JSON Schema (src/catalog-export.ts).
const exporter = await build({
  entryPoints: [join(here, "src/catalog-export.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  alias: { "@": join(here, "src/vendor") },
  logLevel: "error",
  write: false,
});
const catalogJSON = execFileSync("node", ["--input-type=module", "-"], { input: exporter.outputFiles[0].text, encoding: "utf8" });
JSON.parse(catalogJSON);
const swift = join(here, "../../Sources/PennantHostKit/Publishing/CardCatalog+Generated.swift");
writeFileSync(swift, `// Generated by Web/cards/build.mjs from json-render's catalog (Web/cards/src/catalog-export.ts); don't edit.
extension CardCatalog {
    static let generatedJSON = #"""
${catalogJSON}
"""#
}
`);
console.log(`${swift} ${(catalogJSON.length / 1024).toFixed(0)} KB`);
